#!/usr/bin/env node
/**
 * Creates the private owner config for the server (salted PBKDF2-SHA256 hash — the password
 * itself is never stored). Uses only Node's built-in crypto.
 *
 *   npm run owner:hash
 *
 * Then upload the printed file as:
 *   <folder that contains public_html>/offplansale-owner-config.php
 * (one level ABOVE public_html, so it can never be downloaded from the website)
 */
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { createInterface } from 'node:readline'
import { writeFileSync } from 'node:fs'

const ITERATIONS = 600000

function ask(question, hidden = false) {
  return new Promise((resolve) => {
    const rl = createInterface({ input: process.stdin, output: process.stdout, terminal: true })
    if (hidden) {
      rl._writeToOutput = (s) => {
        if (s.includes(question)) rl.output.write(s)
        else rl.output.write('*')
      }
    }
    rl.question(question, (answer) => {
      rl.close()
      if (hidden) process.stdout.write('\n')
      resolve(answer)
    })
  })
}

const username = (process.env.OWNER_USERNAME || (await ask('Owner username: '))).trim()
const password = process.env.OWNER_PASSWORD || (await ask('Owner password (min 12 characters): ', true))
if (!username) {
  console.error('Username is required.')
  process.exit(1)
}
if (password.length < 12) {
  console.error('Please use a password of at least 12 characters.')
  process.exit(1)
}

const salt = randomBytes(16)
const hash = pbkdf2Sync(password, salt, ITERATIONS, 32, 'sha256')
const stored = `pbkdf2_sha256$${ITERATIONS}$${salt.toString('base64')}$${hash.toString('base64')}`

const php = `<?php
// Owner login config for offplansale.com — keep this file OUTSIDE public_html.
// Generated by "npm run owner:hash". The password itself is not stored here.
return [
    'username' => ${JSON.stringify(username)},
    'password_hash' => '${stored}',
    'session_hours' => 8, // how long a login lasts (also signs out after 2 hours of inactivity)
];
`
const out = 'offplansale-owner-config.php'
writeFileSync(out, php, { mode: 0o600 })
console.log(`\nCreated ${out} in this folder (it is git-ignored).`)
console.log('Upload it to the folder that CONTAINS public_html (not inside it), then delete the local copy.')
console.log(`\nOr, instead of the file, set these server environment variables:\n  OWNER_USERNAME=${username}\n  OWNER_PASSWORD_HASH=${stored}`)
